def _load_checkpoint(
    path: Path,
    model: ProNORMST,
    contract_hash: str,
    device: torch.device,
    optimizer: torch.optim.Optimizer | None = None,
    scaler: torch.amp.GradScaler | None = None,
    data_order_generator: torch.Generator | None = None,
) -> dict[str, Any]:
    checkpoint = torch.load(path, map_location=device, weights_only=False)
    if checkpoint.get("schema") != "pro-normst-checkpoint-v1":
        raise ValueError("checkpoint schema is not ProNORMST")
    if checkpoint.get("contract_hash") != contract_hash:
        raise ValueError("checkpoint contract hash is incompatible with this run")
    model.load_state_dict(checkpoint["model"], strict=True)
    if optimizer is not None:
        optimizer.load_state_dict(checkpoint["optimizer"])
    if scaler is not None:
        scaler.load_state_dict(checkpoint["scaler"])
    if data_order_generator is not None:
        restore_rng_state(checkpoint["rng"], data_order_generator)
    return checkpoint


def _state_tree_equal(left: Any, right: Any) -> bool:
    if isinstance(left, torch.Tensor) and isinstance(right, torch.Tensor):
        return left.shape == right.shape and bool(torch.equal(left.cpu(), right.cpu()))
    if isinstance(left, dict) and isinstance(right, dict):
        return left.keys() == right.keys() and all(
            _state_tree_equal(left[key], right[key]) for key in left
        )
    if isinstance(left, (list, tuple)) and isinstance(right, type(left)):
        return len(left) == len(right) and all(
            _state_tree_equal(a, b) for a, b in zip(left, right)
        )
    return left == right


def _verify_smoke_checkpoint(
    *,
    model: ProNORMST,
    optimizer: torch.optim.Optimizer,
    scaler: torch.amp.GradScaler,
    data_order_generator: torch.Generator,
    data: ProNORMSTData,
    banks: dict[str, dict[str, dict[str, tuple[ProMask, ...]]]],
    output_dir: Path,
    device: torch.device,
    use_amp: bool,
    contract_hash: str,
) -> dict[str, Any]:
    """Exercise full resume state and locked-checkpoint prediction after smoke."""

    restored = ProNORMST(
        torch.as_tensor(data.preprocessing.gene_mean_z), variant=model.variant
    ).to(device)
    restored_optimizer, _ = optimizer_for_model(restored)
    restored_scaler = torch.amp.GradScaler(device.type, enabled=use_amp)
    restored_generator = torch.Generator(device="cpu").manual_seed(0)
    checkpoint = _load_checkpoint(
        output_dir / "last.pt",
        restored,
        contract_hash,
        device,
        optimizer=restored_optimizer,
        scaler=restored_scaler,
        data_order_generator=restored_generator,
    )
    first_val = data.roles["val"][0]
    first_mask = banks["val"][first_val.slice_id]["gap"][0]
    current = evaluate_mask(
        model,
        first_val,
        first_mask,
        data.preprocessing.gene_scale,
        data.preprocessing.positive_weight,
        data.preprocessing.detection_rate,
        device,
        use_amp=use_amp,
        return_prediction=True,
    )["prediction_z"]
    reloaded = evaluate_mask(
        restored,
        first_val,
        first_mask,
        data.preprocessing.gene_scale,
        data.preprocessing.positive_weight,
        data.preprocessing.detection_rate,
        device,
        use_amp=use_amp,
        return_prediction=True,
    )["prediction_z"]
    absolute_error = np.abs(current.astype(np.float64) - reloaded.astype(np.float64))
    relative_error = absolute_error / np.maximum(
        np.abs(reloaded.astype(np.float64)), CHECKPOINT_PREDICTION_ATOL
    )
    checks = {
        "model_state_round_trip": _state_tree_equal(
            model.state_dict(), restored.state_dict()
        ),
        "optimizer_state_round_trip": _state_tree_equal(
            optimizer.state_dict(), restored_optimizer.state_dict()
        ),
        "scaler_state_round_trip": _state_tree_equal(
            scaler.state_dict(), restored_scaler.state_dict()
        ),
        "data_order_rng_round_trip": bool(
            torch.equal(
                data_order_generator.get_state(), restored_generator.get_state()
            )
        ),
        "resume_epoch_and_step": (
            int(checkpoint["epoch"]) == 1
            and int(checkpoint["global_step"])
            == OPTIMIZATION_CONTRACT["optimizer_steps_per_epoch"]
        ),
        "locked_checkpoint_prediction": bool(
            np.allclose(
                current,
                reloaded,
                rtol=CHECKPOINT_PREDICTION_RTOL,
                atol=CHECKPOINT_PREDICTION_ATOL,
            )
        ),
        "test_expression_loaded_by_scanpy": all(
            isinstance(item.expression_x, np.ndarray)
            and isinstance(item.expression_z, np.ndarray)
            for item in data.roles["test"]
        ),
    }
    result = {
        "schema": "pro-normst-smoke-verification-v1",
        "passed": all(checks.values()),
        "checks": checks,
        "prediction_tolerance": {
            "rtol": CHECKPOINT_PREDICTION_RTOL,
            "atol": CHECKPOINT_PREDICTION_ATOL,
            "max_abs_error": float(absolute_error.max(initial=0.0)),
            "max_relative_error": float(relative_error.max(initial=0.0)),
        },
        "checkpoint_sha256": file_sha256(output_dir / "last.pt"),
    }
    _write_json(output_dir / "smoke_verification.json", result, allow_replace=False)
    if not result["passed"]:
        raise RuntimeError(f"smoke checkpoint verification failed: {checks}")
    return result


def _model_input(
    item: ProNORMSTSlice,
    mask: ProMask,
    device: torch.device,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
    visible_z = torch.as_tensor(
        item.expression_z[mask.visible_index], dtype=torch.float32, device=device
    ).unsqueeze(0)
    target_z = torch.as_tensor(
        item.expression_z[mask.query_index], dtype=torch.float32, device=device
    ).unsqueeze(0)
    visible_index = torch.as_tensor(mask.visible_index, dtype=torch.long, device=device)
    query_index = torch.as_tensor(mask.query_index, dtype=torch.long, device=device)
    return visible_z, visible_index, query_index, target_z


def _train_one_epoch(
    *,
    model: ProNORMST,
    data: ProNORMSTData,
    geometries: dict[str, MaskGeometry],
    optimizer: torch.optim.Optimizer,
    scaler: torch.amp.GradScaler,
    data_order_generator: torch.Generator,
    device: torch.device,
    use_amp: bool,
    protocol: str,
    fold: str,
    epoch: int,
    global_step: int,
    cycles: int,
    gradient_seen: dict[str, bool],
) -> tuple[int, dict[str, Any], list[dict[str, Any]], dict[str, bool]]:
    model.train()
    train_slices = data.roles["train"]
    positive_weight = torch.as_tensor(
        data.preprocessing.positive_weight, dtype=torch.float32, device=device
    )
    losses = {"ordinary": [], "gap": []}
    mask_records: list[dict[str, Any]] = []
    diagnostics: list[dict[str, Any]] = []
    gradient_norms: list[float] = []
    for cycle in range(cycles):
        global_cycle = epoch * OPTIMIZATION_CONTRACT["cycles_per_epoch"] + cycle
        for family in ("ordinary", "gap"):
            global_step += 1
            lr = learning_rate_for_step(global_step)
            for parameter_group in optimizer.param_groups:
                parameter_group["lr"] = lr
            optimizer.zero_grad(set_to_none=True)
            order = torch.randperm(
                len(train_slices), generator=data_order_generator
            ).tolist()
            diagnostic_step = (
                (epoch == 0 and cycle == 0 and family == "gap")
                or (
                    (epoch + 1) % 5 == 0
                    and cycle == cycles - 1
                    and family == "gap"
                )
            )
            diagnostic_auxiliary = None
            step_losses = []
            for order_offset, slice_offset in enumerate(order):
                item = train_slices[slice_offset]
                identity = make_mask_identity(
                    protocol=protocol,
                    fold=fold,
                    role="train",
                    slice_id=item.slice_id,
                    family=family,
                    mask_index=global_cycle,
                )
                mask = generate_mask(geometries[item.slice_id], identity)
                mask_records.append(_compact_mask_manifest(mask))
                visible_z, visible_index, query_index, target_z = _model_input(
                    item, mask, device
                )
                want_auxiliary = diagnostic_step and order_offset == 0
                with torch.amp.autocast(device_type=device.type, enabled=use_amp):
                    output = model(
                        visible_z,
                        visible_index,
                        query_index,
                        item.geometry(device),
                        return_auxiliary=want_auxiliary,
                        return_diagnostics=want_auxiliary,
                    )
                prediction_z, auxiliary = output if isinstance(output, tuple) else (output, None)
                loss = weighted_gene_smooth_l1(prediction_z, target_z, positive_weight)
                if want_auxiliary and isinstance(auxiliary, dict):
                    local_diagnostics = auxiliary.get("local_diagnostics", {})
                    for state in local_diagnostics.get("round_states", []):
                        if isinstance(state, torch.Tensor) and state.requires_grad:
                            state.retain_grad()
                scaler.scale(loss / len(train_slices)).backward()
                step_losses.append(float(loss.detach().item()))
                if want_auxiliary:
                    diagnostic_auxiliary = auxiliary
            scaler.unscale_(optimizer)
            gradient_norm = torch.nn.utils.clip_grad_norm_(
                [parameter for parameter in model.parameters() if parameter.requires_grad],
                max_norm=1.0,
                error_if_nonfinite=True,
            )
            gradient_norm_value = float(gradient_norm.item())
            gradient_norms.append(gradient_norm_value)
            if not math.isfinite(gradient_norm_value):
                raise FloatingPointError("non-finite gradient norm")
            for name, parameter in model.named_parameters():
                if not parameter.requires_grad or parameter.grad is None:
                    continue
                if not bool(torch.isfinite(parameter.grad).all()):
                    raise FloatingPointError(f"non-finite gradient in {name}")
                if bool((parameter.grad != 0).any()):
                    gradient_seen[name] = True
            scaler.step(optimizer)
            scaler.update()
            losses[family].append(float(np.mean(step_losses)))
            if diagnostic_auxiliary is not None:
                diagnostics.append(
                    {
                        "epoch": epoch + 1,
                        "cycle": cycle + 1,
                        "family": family,
                        "global_step": global_step,
                        **diagnostic_summary(diagnostic_auxiliary, gradient_norm_value),
                    }
                )
    return (
        global_step,
        {
            "ordinary": float(np.mean(losses["ordinary"])),
            "gap": float(np.mean(losses["gap"])),
            "combined": float(0.5 * (np.mean(losses["ordinary"]) + np.mean(losses["gap"]))),
        },
        mask_records,
        {
            **gradient_seen,
            "__diagnostics__": diagnostics,
            "__gradient_norm_mean__": float(np.mean(gradient_norms)),
            "__gradient_norm_max__": float(np.max(gradient_norms)),
        },
    )


def _pilot_gate(validation: dict[str, Any]) -> dict[str, Any]:
    family_status = {}
    passed = True
    for family in ("ordinary", "gap"):
        summary = validation["families"][family]["summary"]
        model_smooth = summary["model"]["smooth_l1"]
        idw_smooth = summary["idw"]["smooth_l1"]
        variance = summary["model"]["variance_ratio_median"]
        family_pass = (
            isinstance(model_smooth, (int, float))
            and isinstance(idw_smooth, (int, float))
            and isinstance(variance, (int, float))
            and model_smooth <= 1.2 * idw_smooth
            and 1e-3 <= variance <= 10.0
        )
        family_status[family] = {
            "passed": family_pass,
            "model_smooth_l1": model_smooth,
            "idw_smooth_l1": idw_smooth,
            "variance_ratio_median": variance,
        }
        passed = passed and family_pass
    return {"passed": passed, "families": family_status}


def _final_loss_bptt_gate(
    history: list[dict[str, Any]], variant: str
) -> dict[str, Any]:
    records = []
    for epoch in history:
        for diagnostic in epoch.get("diagnostics", []):
            norms = diagnostic.get("final_loss_round_state_gradient_norm")
            if isinstance(norms, list):
                records.append(
                    {
                        "epoch": epoch.get("epoch"),
                        "global_step": diagnostic.get("global_step"),
                        "round_gradient_norm": norms,
                    }
                )
    if variant == "global-only":
        return {
            "schema": "pro-normst-final-loss-bptt-v1",
            "applicable": False,
            "passed": True,
            "records": records,
        }
    required_rounds = 1 if variant == "one-shot" else 4
    passed_record = False
    for record in records:
        norms = record["round_gradient_norm"]
        if len(norms) != required_rounds:
            continue
        numeric = [
            float(value)
            for value in norms
            if isinstance(value, (int, float)) and math.isfinite(value)
        ]
        if len(numeric) == required_rounds and all(value > 0 for value in numeric):
            passed_record = True
            break
    return {
        "schema": "pro-normst-final-loss-bptt-v1",
        "applicable": True,
        "required_rounds": required_rounds,
        "passed": passed_record,
        "records": records,
    }


def _prediction_tree_sha256(root: Path) -> str:
    files = sorted(root.rglob("*.npz"))
    if not files:
        raise ValueError(f"test prediction tree is empty: {root}")
    digest = hashlib.sha256()
    for path in files:
        relative = str(path.relative_to(root)).replace("\\", "/")
        digest.update(relative.encode("utf-8"))
        digest.update(file_sha256(path).encode("ascii"))
    return digest.hexdigest()


def _load_committed_test(
    artifact_dir: Path,
    *,
    checkpoint_path: Path,
    contract_hash: str,
    test_data_identity: dict[str, str],
    primary_round: int,
) -> dict[str, Any] | None:
    if not artifact_dir.exists():
        return None
    if not artifact_dir.is_dir():
        raise ValueError(f"test artifact path is not a directory: {artifact_dir}")
    metrics_path = artifact_dir / "test_metrics.json"
    marker_path = artifact_dir / "test_complete.json"
    if not metrics_path.is_file() or not marker_path.is_file():
        raise ValueError("committed test artifact directory is incomplete")
    results = json.loads(metrics_path.read_text(encoding="utf-8"))
    marker = json.loads(marker_path.read_text(encoding="utf-8"))
    expected_checkpoint_hash = file_sha256(checkpoint_path)
    expected_rounds = sorted(key for key in results if key.startswith("round"))
    valid = (
        marker.get("status") == "complete"
        and marker.get("checkpoint_sha256") == expected_checkpoint_hash
        and marker.get("contract_hash") == contract_hash
        and marker.get("test_metrics_sha256") == file_sha256(metrics_path)
        and marker.get("test_expression_x_sha256") == test_data_identity
        and marker.get("primary_round") == primary_round
        and marker.get("round_evidence") == expected_rounds
        and marker.get("prediction_tree_sha256")
        == _prediction_tree_sha256(artifact_dir / "predictions")
        and results.get("_meta", {}).get("contract_hash") == contract_hash
        and results.get("_meta", {}).get("test_expression_x_sha256")
        == test_data_identity
    )
    if not valid:
        raise ValueError("committed test artifacts do not match the locked evaluation")
    return results


def _run_test_once(
    *,
    model: ProNORMST,
    data: ProNORMSTData,
    banks: dict[str, dict[str, dict[str, tuple[ProMask, ...]]]],
    output_dir: Path,
    device: torch.device,
    use_amp: bool,
    checkpoint_path: Path,
    protocol: str,
    contract_hash: str,
) -> dict[str, Any]:
    test_data_identity = test_expression_identity(data)
    primary_round = 4 if model.variant != "one-shot" else 1
    artifact_dir = output_dir / TEST_ARTIFACTS_DIRECTORY
    committed = _load_committed_test(
        artifact_dir,
        checkpoint_path=checkpoint_path,
        contract_hash=contract_hash,
        test_data_identity=test_data_identity,
        primary_round=primary_round,
    )
    if committed is not None:
        return committed

    staging = output_dir / f".{TEST_ARTIFACTS_DIRECTORY}.tmp"
    if staging.exists():
        if not staging.is_dir():
            raise ValueError(f"test staging path is not a directory: {staging}")
        try:
            staged = _load_committed_test(
                staging,
                checkpoint_path=checkpoint_path,
                contract_hash=contract_hash,
                test_data_identity=test_data_identity,
                primary_round=primary_round,
            )
        except (OSError, ValueError):
            shutil.rmtree(staging)
        else:
            os.replace(staging, artifact_dir)
            return staged
    staging.mkdir(parents=False)
    primary = _evaluate_role(
        model,
        data,
        "test",
        banks,
        device,
        use_amp=use_amp,
        output_dir=staging,
        prediction_label=f"test_round{primary_round}",
        round_limit=primary_round,
    )
    results: dict[str, Any] = {
        "_meta": {
            "schema": "pro-normst-test-metrics-v1",
            "contract_hash": contract_hash,
            "test_expression_x_sha256": test_data_identity,
        },
        f"round{primary_round}": primary,
    }
    if protocol == "pair_grouped_lodo" and model.variant == "full":
        for round_limit in (1, 2):
            results[f"round{round_limit}"] = _evaluate_role(
                model,
                data,
                "test",
                banks,
                device,
                use_amp=use_amp,
                output_dir=staging,
                prediction_label=f"test_round{round_limit}",
                round_limit=round_limit,
            )
    metrics_path = staging / "test_metrics.json"
    _write_json(metrics_path, results, allow_replace=False)
    marker_payload = {
        "status": "complete",
        "checkpoint": str(checkpoint_path.resolve()),
        "checkpoint_sha256": file_sha256(checkpoint_path),
        "contract_hash": contract_hash,
        "test_metrics_sha256": file_sha256(metrics_path),
        "test_expression_x_sha256": test_data_identity,
        "primary_round": primary_round,
        "round_evidence": sorted(key for key in results if key.startswith("round")),
        "prediction_tree_sha256": _prediction_tree_sha256(staging / "predictions"),
    }
    _write_json(staging / "test_complete.json", marker_payload, allow_replace=False)
    os.replace(staging, artifact_dir)
    return results


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    device = _device_from_argument(args.device)
    data = prepare_pro_normst_data(args.manifest, args.panel, count_file=args.count_file)
    protocol, fold = _split_identity(data)
    _validate_args(args, protocol)
    seed_initialization(args.seed)
    model = ProNORMST(
        torch.as_tensor(data.preprocessing.gene_mean_z), variant=args.variant
    ).to(device)
    optimizer, parameter_groups = optimizer_for_model(model)
    use_amp = device.type == "cuda"
    scaler = torch.amp.GradScaler(device.type, enabled=use_amp)
    data_order_generator = torch.Generator(device="cpu")
    data_order_generator.manual_seed(OPTIMIZATION_CONTRACT["data_order_seed"])
    geometries = _build_geometries(data)
    banks = _build_fixed_banks(data, geometries, protocol, fold)
    contract_manifest = _contract_manifest(
        args, data, model, protocol, fold, geometries, banks
    )
    contract_hash = _numerical_contract_hash(contract_manifest)
    if protocol == "pair_grouped_lodo":
        _validate_candidate_lock(args.candidate_lock, contract_manifest)
    output_dir = args.output_dir.resolve()

    fresh = not args.resume and not args.predict_only
    if fresh:
        if output_dir.exists():
            raise FileExistsError(f"run directory already exists: {output_dir}")
        output_dir.mkdir(parents=True)
        _save_run_artifacts(
            output_dir,
            args,
            data,
            model,
            parameter_groups,
            protocol,
            fold,
            contract_manifest,
            contract_hash,
            banks,
        )
    else:
        if not output_dir.is_dir():
            raise FileNotFoundError(output_dir)
        _validate_existing_run(
            output_dir, args, data, contract_manifest, contract_hash
        )

    if args.predict_only:
        locked_best = (output_dir / "best.pt").resolve()
        if not locked_best.is_file():
            raise FileNotFoundError(locked_best)
        checkpoint_path = (args.checkpoint or locked_best).resolve()
        if file_sha256(checkpoint_path) != file_sha256(locked_best):
            raise ValueError("predict-only checkpoint must be byte-identical to locked best.pt")
        checkpoint = _load_checkpoint(checkpoint_path, model, contract_hash, device)
        if protocol == "pair_grouped_random_split":
            _write_candidate_lock(output_dir, contract_manifest)
        _run_test_once(
            model=model,
            data=data,
            banks=banks,
            output_dir=output_dir,
            device=device,
            use_amp=use_amp,
            checkpoint_path=checkpoint_path,
            protocol=protocol,
            contract_hash=contract_hash,
        )
        _write_json(
            output_dir / "run_status.json",
            {
                "status": "complete",
                "test_run": True,
                "best_epoch": int(checkpoint["best_epoch"]),
                "best_validation": float(checkpoint["best_value"]),
                "checkpoint_sha256": file_sha256(checkpoint_path),
            },
            allow_replace=False,
        )
        return 0

    start_epoch = 0
    global_step = 0
    best_value = math.inf
    best_epoch = -1
    bad_epochs = 0
    history: list[dict[str, Any]] = []
    gradient_cache: dict[str, float] = {}
    gradient_seen = {name: False for name in model.trainable_parameter_names()}
    if args.resume:
        checkpoint = _load_checkpoint(
            output_dir / "last.pt",
            model,
            contract_hash,
            device,
            optimizer=optimizer,
            scaler=scaler,
            data_order_generator=data_order_generator,
        )
        start_epoch = int(checkpoint["epoch"])
        global_step = int(checkpoint["global_step"])
        best_value = float(checkpoint["best_value"])
        best_epoch = int(checkpoint["best_epoch"])
        bad_epochs = int(checkpoint["bad_epochs"])
        history = checkpoint["history"]
        gradient_cache = checkpoint.get("gradient_cache", {})
        gradient_seen.update(checkpoint.get("gradient_seen", {}))

    cycles = OPTIMIZATION_CONTRACT["cycles_per_epoch"]
    for epoch in range(start_epoch, args.epochs):
        if bad_epochs >= OPTIMIZATION_CONTRACT["early_stopping_patience"]:
            break
        global_step, train_loss, mask_records, gradient_state = _train_one_epoch(
            model=model,
            data=data,
            geometries=geometries,
            optimizer=optimizer,
            scaler=scaler,
            data_order_generator=data_order_generator,
            device=device,
            use_amp=use_amp,
            protocol=protocol,
            fold=fold,
            epoch=epoch,
            global_step=global_step,
            cycles=cycles,
            gradient_seen=gradient_seen,
        )
        diagnostics = gradient_state.pop("__diagnostics__")
        gradient_norm_mean = float(gradient_state.pop("__gradient_norm_mean__"))
        gradient_norm_max = float(gradient_state.pop("__gradient_norm_max__"))
        gradient_seen.update(gradient_state)
        validation = _evaluate_role(
            model, data, "val", banks, device, use_amp=use_amp, detail="summary"
        )
        criterion = float(validation["criterion_weighted_z_smooth_l1"])
        if not math.isfinite(criterion):
            raise FloatingPointError("validation criterion is non-finite")
        gradient_cache[str(epoch + 1)] = gradient_norm_mean
        record = {
            "epoch": epoch + 1,
            "global_step": global_step,
            "train_loss": train_loss,
            "validation": validation,
            "learning_rate": optimizer.param_groups[0]["lr"],
            "gradient_norm_preclip_mean": gradient_norm_mean,
            "gradient_norm_preclip_max": gradient_norm_max,
            "diagnostics": diagnostics,
        }
        history.append(record)
        _write_json(
            output_dir / "training_masks" / f"epoch_{epoch + 1:03d}.json",
            mask_records,
            allow_replace=False,
        )
        improved = criterion < best_value - OPTIMIZATION_CONTRACT["early_stopping_min_delta"]
        if improved:
            best_value = criterion
            best_epoch = epoch + 1
            bad_epochs = 0
        else:
            bad_epochs += 1
        payload = _checkpoint_payload(
            model=model,
            optimizer=optimizer,
            scaler=scaler,
            data_order_generator=data_order_generator,
            contract_hash=contract_hash,
            epoch=epoch + 1,
            global_step=global_step,
            best_value=best_value,
            best_epoch=best_epoch,
            bad_epochs=bad_epochs,
            history=history,
            gradient_cache=gradient_cache,
            gradient_seen=gradient_seen,
        )
        _save_torch(output_dir / "last.pt", payload)
        if improved:
            _save_torch(output_dir / "best.pt", payload)
        _write_json(output_dir / "history.json", history)
        if bad_epochs >= OPTIMIZATION_CONTRACT["early_stopping_patience"]:
            break

    missing_gradient = sorted(name for name, seen in gradient_seen.items() if not seen)
    gradient_gate = {"passed": not missing_gradient, "missing_nonzero_gradient": missing_gradient}
    _write_json(output_dir / "gradient_gate.json", gradient_gate, allow_replace=False)
    if missing_gradient:
        raise RuntimeError(f"trainable parameters never received a nonzero gradient: {missing_gradient}")
    bptt_gate = _final_loss_bptt_gate(history, model.variant)
    _write_json(
        output_dir / "final_loss_bptt_gate.json",
        bptt_gate,
        allow_replace=False,
    )
    if not bptt_gate["passed"]:
        raise RuntimeError("final gene loss did not verify full-BPTT through local rounds")
    if args.smoke:
        smoke_verification = _verify_smoke_checkpoint(
            model=model,
            optimizer=optimizer,
            scaler=scaler,
            data_order_generator=data_order_generator,
            data=data,
            banks=banks,
            output_dir=output_dir,
            device=device,
            use_amp=use_amp,
            contract_hash=contract_hash,
        )
        _write_json(
            output_dir / "run_status.json",
            {
                "status": "smoke-complete",
                "evidence": "engineering-only",
                "test_run": False,
                "smoke_verification_passed": smoke_verification["passed"],
                "best_epoch": best_epoch,
                "best_validation": best_value,
            },
            allow_replace=False,
        )
        return 0

    best_path = output_dir / "best.pt"
    best_checkpoint = _load_checkpoint(best_path, model, contract_hash, device)
    best_validation = history[best_epoch - 1]["validation"]
    first_val = data.roles["val"][0]
    first_mask = banks["val"][first_val.slice_id]["gap"][0]
    diagnostic_record = evaluate_mask(
        model,
        first_val,
        first_mask,
        data.preprocessing.gene_scale,
        data.preprocessing.positive_weight,
        data.preprocessing.detection_rate,
        device,
        use_amp=use_amp,
        return_auxiliary=True,
    )
    final_diagnostics = diagnostic_summary(
        diagnostic_record["auxiliary"],
        best_checkpoint.get("gradient_cache", {}).get(str(best_epoch)),
    )
    _write_json(output_dir / "best_diagnostics.json", final_diagnostics, allow_replace=False)

    if protocol == "pair_grouped_random_split":
        gate = _pilot_gate(best_validation)
        _write_json(output_dir / "pilot_gate.json", gate, allow_replace=False)
        if not gate["passed"]:
            _write_json(
                output_dir / "run_status.json",
                {
                    "status": "pilot-health-gate-failed",
                    "test_run": False,
                    "best_epoch": best_epoch,
                    "best_validation": best_value,
                },
                allow_replace=False,
            )
            return 0
        _write_candidate_lock(output_dir, contract_manifest)

    _run_test_once(
        model=model,
        data=data,
        banks=banks,
        output_dir=output_dir,
        device=device,
        use_amp=use_amp,
        checkpoint_path=best_path,
        protocol=protocol,
        contract_hash=contract_hash,
    )
    _write_json(
        output_dir / "run_status.json",
        {
            "status": "complete",
            "test_run": True,
            "best_epoch": best_epoch,
            "best_validation": best_value,
            "checkpoint_sha256": file_sha256(best_path),
        },
        allow_replace=False,
    )
    return 0


