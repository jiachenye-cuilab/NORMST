def _atomic_bytes(path: Path, writer) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    handle = tempfile.NamedTemporaryFile(
        prefix=f".{path.name}.", suffix=".tmp", dir=path.parent, delete=False
    )
    temporary = Path(handle.name)
    handle.close()
    try:
        writer(temporary)
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def _write_json(path: Path, payload: Any, *, allow_replace: bool = True) -> None:
    if path.exists() and not allow_replace:
        existing = json.loads(path.read_text(encoding="utf-8"))
        if canonical_json(existing) != canonical_json(payload):
            raise FileExistsError(f"refusing to replace incompatible artifact: {path}")
        return

    def write(temporary: Path) -> None:
        temporary.write_text(
            json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
            encoding="utf-8",
        )

    _atomic_bytes(path, write)


def _save_torch(path: Path, payload: dict[str, Any]) -> None:
    _atomic_bytes(path, lambda temporary: torch.save(payload, temporary))


def _device_from_argument(value: str) -> torch.device:
    device = torch.device(value)
    if device.type == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA was requested but is unavailable")
    if device.type not in {"cpu", "cuda"}:
        raise ValueError("ProNORMST supports only CPU or CUDA devices")
    return device


def _split_identity(data: ProNORMSTData) -> tuple[str, str]:
    protocol = str(data.split_metadata.get("protocol", ""))
    if protocol == "pair_grouped_lodo":
        fold = str(data.split_metadata.get("fold", ""))
        expected = {"train": 4, "val": 4, "test": 4}
        if not fold:
            raise ValueError("LODO manifest is missing fold identity")
    elif protocol == "pair_grouped_random_split":
        fold = f"pilot_seed{data.split_metadata.get('split_seed', 'unknown')}"
        expected = {"train": 8, "val": 2, "test": 2}
    else:
        raise ValueError(f"unsupported split protocol: {protocol}")
    actual = {role: len(items) for role, items in data.roles.items()}
    if actual != expected:
        raise ValueError(f"split role sizes {actual} do not match {expected}")
    return protocol, fold


def _validate_args(args: argparse.Namespace, protocol: str) -> None:
    if args.resume and args.predict_only:
        raise ValueError("--resume and --predict-only are mutually exclusive")
    if args.smoke and (args.resume or args.predict_only):
        raise ValueError("--smoke cannot be combined with resume or predict-only")
    if args.smoke:
        if args.epochs not in {1, 50}:
            raise ValueError("--smoke fixes the run to one epoch")
        args.epochs = 1
    elif args.epochs != 50:
        raise ValueError("contracted pilot/formal training uses --epochs 50; use --smoke for one epoch")
    allowed = {2027} if protocol == "pair_grouped_random_split" else {2027, 2028, 2029}
    if args.seed not in allowed:
        raise ValueError(f"initialization seed must be one of {sorted(allowed)} for {protocol}")
    if protocol == "pair_grouped_random_split" and args.variant != "full":
        raise ValueError("the contracted 8/2/2 pilot trains only the full ProNORMST candidate")
    if protocol == "pair_grouped_random_split" and args.candidate_lock is not None:
        raise ValueError("pilot runs must not consume a candidate lock")
    if protocol == "pair_grouped_lodo" and args.candidate_lock is None:
        raise ValueError("formal LODO runs require --candidate-lock from a passed pilot")


def _build_geometries(data: ProNORMSTData) -> dict[str, MaskGeometry]:
    return {
        item.slice_id: build_mask_geometry(item.neighbor_index)
        for items in data.roles.values()
        for item in items
    }


def _build_fixed_banks(
    data: ProNORMSTData,
    geometries: dict[str, MaskGeometry],
    protocol: str,
    fold: str,
) -> dict[str, dict[str, dict[str, tuple[ProMask, ...]]]]:
    banks: dict[str, dict[str, dict[str, tuple[ProMask, ...]]]] = {"val": {}, "test": {}}
    for role in ("val", "test"):
        for item in data.roles[role]:
            banks[role][item.slice_id] = {
                family: fixed_mask_bank(
                    geometries[item.slice_id],
                    protocol=protocol,
                    fold=fold,
                    role=role,
                    slice_id=item.slice_id,
                    family=family,
                )
                for family in ("ordinary", "gap")
            }
    return banks


def _compact_mask_manifest(mask: ProMask) -> dict[str, Any]:
    unique_depth, depth_count = np.unique(mask.depth, return_counts=True)
    unique_provenance, provenance_count = np.unique(mask.provenance, return_counts=True)
    return {
        "identity": mask.identity,
        "n_target": mask.n_target,
        "n_query": int(mask.query_index.size),
        "realized_fraction": mask.realized_fraction,
        "provenance_counts": {
            str(key): int(value) for key, value in zip(unique_provenance, provenance_count)
        },
        "depth_counts": {str(int(key)): int(value) for key, value in zip(unique_depth, depth_count)},
        "hole_sizes": [len(hole.nodes) for hole in mask.holes],
        "hole_radii": [hole.radius for hole in mask.holes],
        "query_components": int(np.unique(mask.query_component).size),
        "substream_seeds": mask.substream_seeds,
    }


def _save_run_artifacts(
    output_dir: Path,
    args: argparse.Namespace,
    data: ProNORMSTData,
    model: ProNORMST,
    parameter_groups: dict[str, list[str]],
    protocol: str,
    fold: str,
    contract_manifest: dict[str, Any],
    contract_hash: str,
    banks: dict[str, dict[str, dict[str, tuple[ProMask, ...]]]],
) -> None:
    config = {
        "schema": "pro-normst-run-config-v2",
        "model": "pro-normst",
        "variant": args.variant,
        "manifest": str(args.manifest.resolve()),
        "panel": str(args.panel.resolve()),
        "count_file": args.count_file,
        "output_dir": str(output_dir),
        "initialization_seed": args.seed,
        "data_order_seed": 2027,
        "protocol": protocol,
        "fold": fold,
        "epochs": args.epochs,
        "smoke": bool(args.smoke),
        "evidence_tier": "real-data-smoke" if args.smoke else ("pilot" if protocol == "pair_grouped_random_split" else "formal-lodo"),
        "contract_hash": contract_hash,
        "candidate_lock": (
            str(args.candidate_lock.resolve()) if args.candidate_lock is not None else None
        ),
    }
    _write_json(output_dir / "config.json", config, allow_replace=False)
    _write_json(output_dir / "contract_manifest.json", contract_manifest, allow_replace=False)
    _write_json(output_dir / "optimizer_parameter_groups.json", parameter_groups, allow_replace=False)
    _write_json(output_dir / "split_metadata.json", data.split_metadata, allow_replace=False)
    _write_json(
        output_dir / "split_manifest.snapshot.json",
        json.loads(args.manifest.resolve().read_text(encoding="utf-8")),
        allow_replace=False,
    )
    _write_json(output_dir / "environment.json", {
        "python": __import__("sys").version,
        "torch": str(torch.__version__),
        "numpy": str(np.__version__),
        "cuda": torch.version.cuda,
        "device_request": args.device,
    }, allow_replace=False)
    (output_dir / "genes.txt").write_text("\n".join(data.preprocessing.gene_ids) + "\n", encoding="utf-8")
    np.savez(
        output_dir / "preprocessing.npz",
        gene_scale=data.preprocessing.gene_scale,
        detection_rate=data.preprocessing.detection_rate,
        positive_weight=data.preprocessing.positive_weight,
        gene_mean_z=data.preprocessing.gene_mean_z,
    )
    for role, role_banks in banks.items():
        for slice_id, family_banks in role_banks.items():
            for family, masks in family_banks.items():
                for index, mask in enumerate(masks):
                    _write_json(
                        output_dir / "mask_banks" / role / slice_id / family / f"mask_{index:02d}.json",
                        mask.manifest(),
                        allow_replace=False,
                    )


def _validate_existing_run(
    output_dir: Path,
    args: argparse.Namespace,
    data: ProNORMSTData,
    contract_manifest: dict[str, Any],
    contract_hash: str,
) -> None:
    config = json.loads((output_dir / "config.json").read_text(encoding="utf-8"))
    if config.get("contract_hash") != contract_hash:
        raise ValueError("run directory contract is incompatible with current arguments/data")
    saved_contract = json.loads(
        (output_dir / "contract_manifest.json").read_text(encoding="utf-8")
    )
    saved_numerical = _numerical_contract(saved_contract)
    current_numerical = _numerical_contract(contract_manifest)
    if canonical_json(saved_numerical) != canonical_json(current_numerical):
        raise ValueError("saved numerical compatibility contract has changed")
    if _audit_provenance(saved_contract) != _audit_provenance(contract_manifest):
        warnings.warn(
            "audit provenance changed while the numerical compatibility contract remained stable",
            RuntimeWarning,
            stacklevel=2,
        )
    saved_genes = tuple(
        line.strip()
        for line in (output_dir / "genes.txt").read_text(encoding="utf-8").splitlines()
        if line.strip()
    )
    if saved_genes != data.preprocessing.gene_ids:
        raise ValueError("saved gene order is incompatible")
    with np.load(output_dir / "preprocessing.npz") as saved:
        for name in ("gene_scale", "detection_rate", "positive_weight", "gene_mean_z"):
            if not np.array_equal(saved[name], getattr(data.preprocessing, name)):
                raise ValueError(f"saved preprocessing artifact changed: {name}")
    current_split = json.loads(args.manifest.resolve().read_text(encoding="utf-8"))
    saved_split = json.loads(
        (output_dir / "split_manifest.snapshot.json").read_text(encoding="utf-8")
    )
    if canonical_json(current_split) != canonical_json(saved_split):
        raise ValueError("saved split manifest is incompatible")


def _contract_manifest(
    args: argparse.Namespace,
    data: ProNORMSTData,
    model: ProNORMST,
    protocol: str,
    fold: str,
    geometries: dict[str, MaskGeometry],
    banks: dict[str, dict[str, dict[str, tuple[ProMask, ...]]]],
) -> dict[str, Any]:
    def array_hash(value: np.ndarray) -> str:
        array = np.ascontiguousarray(value)
        digest = hashlib.sha256()
        digest.update(str(array.dtype).encode("ascii"))
        digest.update(canonical_json(list(array.shape)).encode("ascii"))
        digest.update(array.tobytes(order="C"))
        return digest.hexdigest()

    slice_contract = {}
    for role, slices in data.roles.items():
        for item in slices:
            item_contract = {
                "role": role,
                "barcodes_sha256": canonical_sha256(list(item.barcodes)),
                "full_xy_sha256": array_hash(item.full_xy.astype("<f4")),
                "neighbor_index_sha256": array_hash(
                    geometries[item.slice_id].neighbor_index.astype("<i8")
                ),
                "native_scale": item.native_scale,
                "source_barcodes_sha256": item.source_barcodes_sha256,
                "source_gex_gene_ids_sha256": item.source_gex_gene_ids_sha256,
                "source_panel_indices_sha256": item.source_panel_indices_sha256,
            }
            if role == "test":
                item_contract["expression_access"] = (
                    "loaded_read_only_excluded_from_fit_and_model_selection"
                )
            else:
                item_contract["expression_access"] = "materialized_before_training"
            item_contract["expression_x_sha256"] = array_hash(
                item.expression_x.astype("<f4")
            )
            slice_contract[item.slice_id] = item_contract
    fixed_bank_contract = {
        role: {
            slice_id: {
                family: [array_hash(mask.query_index.astype("<i8")) for mask in masks]
                for family, masks in family_banks.items()
            }
            for slice_id, family_banks in role_banks.items()
        }
        for role, role_banks in banks.items()
    }
    return {
        "schema": "pro-normst-training-contract-v2",
        "numerical_implementation_schema": NUMERICAL_IMPLEMENTATION_SCHEMA,
        "implementation_sha256": {
            str(path.relative_to(SOURCE_ROOT)).replace("\\", "/"): file_sha256(path)
            for path in (
                SOURCE_ROOT / "train.py",
                SOURCE_ROOT / "models" / "pro_normst.py",
                SOURCE_ROOT / "models" / "progressive_normst.py",
                SOURCE_ROOT / "datasets" / "pro_normst.py",
                SOURCE_ROOT / "training" / "pro_normst_masks.py",
                SOURCE_ROOT / "training" / "pro_normst_engine.py",
                SOURCE_ROOT / "training" / "pro_normst.py",
                SOURCE_ROOT / "training" / "pro_normst_acceptance.py",
            )
        },
        "model": model.contract_manifest(),
        "preprocessing": data.preprocessing.manifest(),
        "mask_schema": MASK_SCHEMA,
        "fixed_mask_banks": fixed_bank_contract,
        "slice_data_and_geometry": slice_contract,
        "loss_schema": "gene-equal-target-weighted-smooth-l1-beta1-v1",
        "metric_schema": "raw-x-model-idw-stratified-v1",
        "optimization": OPTIMIZATION_CONTRACT,
        "split": {
            "protocol": protocol,
            "fold": fold,
            "role_sizes": {role: len(items) for role, items in data.roles.items()},
        },
        "run": {
            "variant": args.variant,
            "initialization_seed": args.seed,
            "smoke": bool(args.smoke),
            "epochs": args.epochs,
            "precision": "cuda-fp16-amp" if str(args.device).startswith("cuda") else "cpu-fp32",
            "candidate_lock_sha256": (
                file_sha256(args.candidate_lock.resolve())
                if args.candidate_lock is not None
                else None
            ),
        },
        "runtime": {"torch": str(torch.__version__), "numpy": str(np.__version__)},
    }


