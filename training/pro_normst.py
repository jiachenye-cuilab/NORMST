def _evaluate_role(
    model: ProNORMST,
    data: ProNORMSTData,
    role: str,
    banks: dict[str, dict[str, dict[str, tuple[ProMask, ...]]]],
    device: torch.device,
    *,
    use_amp: bool,
    output_dir: Path | None = None,
    prediction_label: str | None = None,
    round_limit: int | None = None,
    detail: str = "full",
) -> dict[str, Any]:
    if detail not in {"full", "summary"}:
        raise ValueError("evaluation detail must be 'full' or 'summary'")
    model.eval()
    family_output: dict[str, Any] = {}
    for family in ("ordinary", "gap"):
        slice_summaries = []
        slice_output: dict[str, Any] = {}
        for item in data.roles[role]:
            records = []
            for mask_offset, mask in enumerate(banks[role][item.slice_id][family]):
                save_prediction = output_dir is not None and prediction_label is not None
                record = evaluate_mask(
                    model,
                    item,
                    mask,
                    data.preprocessing.gene_scale,
                    data.preprocessing.positive_weight,
                    data.preprocessing.detection_rate,
                    device,
                    use_amp=use_amp,
                    round_limit=round_limit,
                    return_prediction=save_prediction,
                )
                if save_prediction:
                    prediction_path = (
                        output_dir
                        / "predictions"
                        / prediction_label
                        / item.slice_id
                        / family
                        / f"mask_{mask_offset:02d}.npz"
                    )
                    if prediction_path.exists():
                        raise FileExistsError(f"refusing to overwrite prediction: {prediction_path}")
                    prediction_path.parent.mkdir(parents=True, exist_ok=True)
                    np.savez_compressed(
                        prediction_path,
                        prediction_z=record.pop("prediction_z"),
                        prediction_x=record.pop("prediction_x"),
                        target_x=record.pop("target_x"),
                        idw_x=record.pop("idw_x"),
                        query_index=mask.query_index,
                        visible_index=mask.visible_index,
                        provenance=mask.provenance,
                        depth=mask.depth,
                    )
                records.append(_minimal_metric_record(record))
            summary = aggregate_slice_mask_records(records)
            slice_summaries.append(summary)
            if detail == "full":
                slice_output[item.slice_id] = {"summary": summary, "masks": records}
        family_summary = mean_slice_summaries(slice_summaries)
        family_output[family] = {"summary": family_summary}
        if detail == "full":
            family_output[family]["slices"] = slice_output
    criterion = float(
        0.5
        * (
            family_output["ordinary"]["summary"]["weighted_z_smooth_l1"]
            + family_output["gap"]["summary"]["weighted_z_smooth_l1"]
        )
    )
    return {
        "role": role,
        "round_limit": round_limit,
        "criterion_weighted_z_smooth_l1": criterion,
        "families": family_output,
    }


